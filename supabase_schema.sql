create table if not exists public.style_profiles (
    user_id uuid primary key references auth.users(id) on delete cascade,
    style_data jsonb not null default '{}'::jsonb,
    updated_at timestamptz not null default now()
);

create table if not exists public.writing_records (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    kind text not null default 'coaching',
    situation text,
    settings jsonb not null default '{}'::jsonb,
    draft text not null default '',
    feedback text not null default '',
    created_at timestamptz not null default now()
);

alter table public.style_profiles enable row level security;
alter table public.writing_records enable row level security;

drop policy if exists "Users can view own style profile" on public.style_profiles;
create policy "Users can view own style profile" on public.style_profiles
for select to authenticated using (auth.uid() = user_id);

drop policy if exists "Users can insert own style profile" on public.style_profiles;
create policy "Users can insert own style profile" on public.style_profiles
for insert to authenticated with check (auth.uid() = user_id);

drop policy if exists "Users can update own style profile" on public.style_profiles;
create policy "Users can update own style profile" on public.style_profiles
for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "Users can view own writing records" on public.writing_records;
create policy "Users can view own writing records" on public.writing_records
for select to authenticated using (auth.uid() = user_id);

drop policy if exists "Users can insert own writing records" on public.writing_records;
create policy "Users can insert own writing records" on public.writing_records
for insert to authenticated with check (auth.uid() = user_id);

create index if not exists writing_records_user_created_idx
on public.writing_records (user_id, created_at desc);
